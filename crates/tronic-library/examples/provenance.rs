//! Prints the provenance list of the built-in library as Markdown:
//! `cargo run -p tronic-library --example provenance > docs/LIBRARY_PROVENANCE.md`

fn main() {
    println!("# Herkunft der Bauteilbibliothek\n");
    println!("## Symbole\n");
    println!("<!-- Generated by crates/tronic-library/examples/provenance.rs. -->\n");
    println!("Alle Symbole wurden für dieses Projekt neu gezeichnet. **Geprüft** bedeutet: Eine Person hat die Pinbelegung gegen das Datenblatt geprüft. Das steht für alle Symbole noch aus.\n");
    println!("| ID | Name | Kategorie | Pins | Quelle | Autor | Lizenz | Geprüft |");
    println!("|---|---|---|---|---|---|---|---|");
    for symbol in tronic_library::builtin() {
        println!(
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            symbol.id,
            symbol.name,
            symbol.category,
            symbol.pins.len(),
            symbol.provenance.source,
            symbol.provenance.author,
            symbol.provenance.license,
            if symbol.provenance.reviewed {
                "ja"
            } else {
                "nein"
            },
        );
    }
    println!("\n## Footprints\n");
    println!("Maße sind typische Werte gängiger Gehäuse, **nicht gegen Herstellerzeichnungen oder IPC-7351 geprüft**.\n");
    println!("| ID | Name | Pads | Quelle | Autor | Lizenz | Geprüft |");
    println!("|---|---|---|---|---|---|---|");
    for footprint in tronic_library::footprints() {
        println!(
            "| `{}` | {} | {} | {} | {} | {} | {} |",
            footprint.id,
            footprint.name,
            footprint.pads.len(),
            footprint.provenance.source,
            footprint.provenance.author,
            footprint.provenance.license,
            if footprint.provenance.reviewed {
                "ja"
            } else {
                "nein"
            },
        );
    }
}
