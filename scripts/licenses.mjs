#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md, THIRD_PARTY_NOTICES.md and
// SOFTWARE_BILL_OF_MATERIALS.md from the real dependency graph.
//
//   node scripts/licenses.mjs           regenerate the files
//   node scripts/licenses.mjs --check   also fail on license policy violations
//
// Scope: everything that ships in the application, meaning Rust crates of the
// desktop binary for all target platforms and the production npm packages.
// Development tools do not ship and are covered by cargo-deny/npm audit only.
//
// A clean result is a technical precondition for a release, not a legal
// approval. See IP_COMPLIANCE.md.
import { execFileSync, execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const UI = join(repo, "apps/desktop");

// SPDX ids accepted without further review. Keep in sync with deny.toml.
const ALLOWED = new Set([
  "MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause",
  "ISC", "Zlib", "0BSD", "CC0-1.0", "Unlicense", "BSL-1.0", "Unicode-3.0", "CDLA-Permissive-2.0",
  "MPL-2.0",
]);

const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright|authors)([-._].*)?$/i;

/** True if an SPDX expression can be satisfied with allowed licenses only. */
export function licenseAllowed(expression) {
  if (!expression) return false;
  const normalized = expression.replace(/\s*\/\s*/g, " OR ").trim();
  return normalized
    .split(/\s+OR\s+/i)
    .map((option) => option.replace(/[()]/g, "").trim())
    .some((option) =>
      option
        .split(/\s+AND\s+/i)
        .every((id) => ALLOWED.has(id.trim())),
    );
}

function licenseFiles(directory) {
  if (!directory || !existsSync(directory)) return [];
  return readdirSync(directory)
    .filter((name) => LICENSE_FILE.test(name) && statSync(join(directory, name)).isFile())
    .sort()
    .map((name) => ({ name, text: readFileSync(join(directory, name), "utf8").trim() }));
}

function shipsInDesktop(metadata) {
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  // The desktop application, and the cloud service for those who run it themselves.
  const roots = metadata.packages.filter((pkg) => ["troniccad-desktop", "tronic-cloud"].includes(pkg.name));
  const seen = new Set();
  const pending = roots.map((pkg) => pkg.id);
  while (pending.length) {
    const id = pending.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      // Build scripts and macros run on the build machine, but generated code
      // can carry their licenses into the binary, so they count as well.
      if (dep.dep_kinds.some((kind) => kind.kind !== "dev")) pending.push(dep.pkg);
    }
  }
  return seen;
}

function rustPackages() {
  const metadata = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: repo,
      maxBuffer: 256 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    }).toString(),
  );
  const shipped = shipsInDesktop(metadata);
  return metadata.packages
    .filter((pkg) => shipped.has(pkg.id) && pkg.source)
    .map((pkg) => ({
      ecosystem: "crates.io",
      name: pkg.name,
      version: pkg.version,
      license: pkg.license ?? (pkg.license_file ? `SEE FILE ${pkg.license_file}` : null),
      authors: (pkg.authors ?? []).join(", "),
      origin: pkg.repository ?? pkg.source,
      directory: dirname(pkg.manifest_path),
    }));
}

function npmPackages() {
  const listing = execSync("npm ls --omit=dev --all --parseable", {
    cwd: UI,
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  }).toString();
  return [...new Set(listing.split(/\r?\n/).filter(Boolean))]
    .filter((directory) => resolve(directory) !== resolve(UI))
    .map((directory) => {
      const manifest = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
      const author = typeof manifest.author === "string" ? manifest.author : manifest.author?.name;
      const repository = manifest.repository?.url ?? manifest.repository;
      return {
        ecosystem: "npm",
        name: manifest.name,
        version: manifest.version,
        license: typeof manifest.license === "string" ? manifest.license : null,
        authors: author ?? "",
        origin: repository ?? `https://www.npmjs.com/package/${manifest.name}`,
        directory,
      };
    });
}

const generated = (when) =>
  `<!-- Generated by scripts/licenses.mjs. Do not edit by hand. -->\n\n> Stand: ${when}. Automatisch aus dem Abhängigkeitsgraphen erzeugt. Keine rechtliche Freigabe, siehe [IP_COMPLIANCE.md](IP_COMPLIANCE.md).\n`;

const packages = [...rustPackages(), ...npmPackages()].sort(
  (a, b) => a.ecosystem.localeCompare(b.ecosystem) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);
const violations = packages.filter((pkg) => !licenseAllowed(pkg.license));
const withoutFile = [];
const when = new Date().toISOString().slice(0, 10);

// THIRD_PARTY_LICENSES.md
const counts = new Map();
for (const pkg of packages) counts.set(pkg.license ?? "UNBEKANNT", (counts.get(pkg.license ?? "UNBEKANNT") ?? 0) + 1);
let licenses = `# Third-Party Licenses\n\n${generated(when)}\n`;
licenses += `Ausgelieferte Fremdkomponenten: **${packages.length}**. Lizenzverstöße gegen die Positivliste: **${violations.length}**.\n\n`;
licenses += "## Lizenzausdrücke\n\n| Lizenz | Pakete |\n|---|---|\n";
for (const [license, count] of [...counts].sort((a, b) => b[1] - a[1])) licenses += `| ${license} | ${count} |\n`;
if (violations.length) {
  licenses += "\n## Ungeklärt, blockiert jedes Release\n\n";
  for (const pkg of violations) licenses += `- ${pkg.name} ${pkg.version}: ${pkg.license ?? "keine Angabe"}\n`;
}
licenses += "\n## Komponenten\n\n| Paket | Version | Quelle | Lizenz |\n|---|---|---|---|\n";
for (const pkg of packages) licenses += `| ${pkg.name} | ${pkg.version} | ${pkg.ecosystem} | ${pkg.license ?? "UNBEKANNT"} |\n`;
writeFileSync(join(repo, "THIRD_PARTY_LICENSES.md"), licenses);

// SOFTWARE_BILL_OF_MATERIALS.md
let sbom = `# Software Bill of Materials\n\n${generated(when)}\n`;
sbom += "Nur ausgelieferte Komponenten, für alle Zielplattformen. Native Systembibliotheken (WebView2, WebKitGTK, GTK) werden nicht mitgeliefert, sondern vom Betriebssystem bezogen.\n\n";
sbom += "| Ökosystem | Name | Version | Lizenz | Hersteller/Autoren | Herkunft |\n|---|---|---|---|---|---|\n";
const cell = (text) => String(text ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
for (const pkg of packages) {
  sbom += `| ${pkg.ecosystem} | ${cell(pkg.name)} | ${cell(pkg.version)} | ${cell(pkg.license)} | ${cell(pkg.authors)} | ${cell(pkg.origin)} |\n`;
}
writeFileSync(join(repo, "SOFTWARE_BILL_OF_MATERIALS.md"), sbom);

// sbom.cdx.json: the same list for machines, as CycloneDX. No time in it, so that the
// file only changes when the components do.
const purl = (pkg) => {
  const name = pkg.name.startsWith("@") ? `%40${pkg.name.slice(1)}` : pkg.name;
  return `pkg:${pkg.ecosystem === "npm" ? "npm" : "cargo"}/${name}@${pkg.version}`;
};
const cyclonedx = {
  bomFormat: "CycloneDX",
  specVersion: "1.5",
  version: 1,
  metadata: { component: { type: "application", name: "TronicCAD" } },
  components: packages.map((pkg) => ({
    type: "library",
    name: pkg.name,
    version: pkg.version,
    purl: purl(pkg),
    ...(pkg.license ? { licenses: [{ expression: pkg.license }] } : {}),
    ...(pkg.authors ? { author: cell(pkg.authors) } : {}),
  })),
};
writeFileSync(join(repo, "sbom.cdx.json"), `${JSON.stringify(cyclonedx, null, 2)}\n`);

// THIRD_PARTY_NOTICES.md: full texts, identical texts printed once.
const texts = new Map();
for (const pkg of packages) {
  const files = licenseFiles(pkg.directory);
  if (files.length === 0) withoutFile.push(pkg);
  for (const file of files) {
    const key = createHash("sha256").update(file.text).digest("hex");
    if (!texts.has(key)) texts.set(key, { text: file.text, users: new Set() });
    texts.get(key).users.add(`${pkg.name} ${pkg.version}`);
  }
}
let notices = `# Third-Party Notices\n\n${generated(when)}\n`;
if (withoutFile.length) {
  notices += `## Ohne mitgelieferte Lizenzdatei (${withoutFile.length})\n\nDiese Pakete nennen ihre Lizenz nur in den Metadaten. Vor einem Release sind Urheberrechtshinweise manuell aus dem jeweiligen Repository zu ergänzen.\n\n`;
  for (const pkg of withoutFile) notices += `- ${pkg.name} ${pkg.version} (${pkg.license ?? "UNBEKANNT"}): ${cell(pkg.origin)}\n`;
  notices += "\n";
}
notices += "## Lizenztexte\n\n";
for (const { text, users } of [...texts.values()].sort((a, b) => b.users.size - a.users.size)) {
  notices += `### Gilt für\n\n${[...users].sort().join(", ")}\n\n\`\`\`text\n${text.replace(/```/g, "'''")}\n\`\`\`\n\n`;
}
// Not a package of either ecosystem, but part of what the Windows installer consists of.
notices += `\n## NSIS and nsis_tauri_utils (Windows installer)\n\nThe Windows installer is made with NSIS and contains its installer code. nsis_tauri_utils (github.com/tauri-apps/nsis-tauri-utils) is under MIT or Apache-2.0.\n\n\`\`\`\n${readFileSync(join(repo, "assets/third-party/NSIS-COPYING.txt"), "utf8").trim()}\n\`\`\`\n`;
writeFileSync(join(repo, "THIRD_PARTY_NOTICES.md"), notices);

console.log(`${packages.length} shipped components, ${counts.size} license expressions`);
console.log(`${withoutFile.length} without a license file, ${violations.length} policy violations`);
for (const pkg of violations) console.error(`VIOLATION ${pkg.ecosystem} ${pkg.name} ${pkg.version}: ${pkg.license ?? "unknown"}`);
if (check && violations.length) process.exit(1);
